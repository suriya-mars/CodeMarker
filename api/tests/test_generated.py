"""Generated code is left out of the graph, and every skip is reported.

Generated files are written by tools and never read by people, so summarising them
pays for nothing. But a "generated" header is easy to fake, so a skipped file is
always counted, and named when a commit changes it.
"""

import os
import subprocess

import pytest

import impact
import parsing

AUTO = "// <auto-generated>\n//   This code was generated by a tool.\n// </auto-generated>\n"
CS = "namespace A {{ public class {0} {{ public void Run() {{ }} }} }}\n"
PY = "def run():\n    return 1\n"


def _repo(tmp_path, files):
    for rel, text in files.items():
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return str(tmp_path)


def _indexed(root):
    skipped = []
    files = {os.path.relpath(p, root).replace(os.sep, "/")
             for p in parsing.iter_source_files(root, skipped)}
    return files, dict(skipped)


@pytest.mark.parametrize(("rel", "text"), [
    ("Proxy.cs", AUTO + CS.format("Proxy")),
    ("Props/Resources.Designer.cs", CS.format("Resources")),
    ("Forms/Main.Designer.cs", CS.format("Main")),
    ("Data/AppModelSnapshot.cs", CS.format("Snap")),
    ("Data/Migrations/20240101_Init.cs", CS.format("Init")),
    ("Service References/Billing/Reference.cs", CS.format("Ref")),
    ("orders/migrations/0001_initial.py", "# Generated by Django 5.0\n" + PY),
    ("api/orders_pb2.py", PY),
    ("api/orders_pb2_grpc.py", PY),
    ("api/schema.py", "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n" + PY),
    ("gen/client.py", "# Code generated by openapi-generator. DO NOT EDIT.\n" + PY),
    ("ui/relay.js", "/**\n * @generated SignedSource<<abc>>\n */\nfunction q() {}\n"),
    ("alembic/versions/abc_add.py", PY),
])
def test_generated_files_are_skipped(tmp_path, rel, text):
    root = _repo(tmp_path, {rel: text, "real.py": PY})
    files, skipped = _indexed(root)
    assert files == {"real.py"}
    assert rel in skipped and skipped[rel].startswith("generated")


@pytest.mark.parametrize(("rel", "text"), [
    # WebForms designer files declare the page's controls and are merged into the page
    ("Web/Default.aspx.designer.cs", AUTO + CS.format("Default")),
    ("Web/Nav.ascx.designer.cs", AUTO + CS.format("Nav")),
    ("Web/Site.master.designer.cs", AUTO + CS.format("Site")),
    # ordinary code that merely talks about generating things
    ("ids.py", '"""Returns generated ids. Do not edit the counter by hand."""\n' + PY),
    ("report.py", "# This report is generated nightly\n" + PY),
    ("generator.py", "def generated_code():\n    return 'do not edit'\n"),
])
def test_ordinary_code_is_kept(tmp_path, rel, text):
    files, skipped = _indexed(_repo(tmp_path, {rel: text}))
    assert files == {rel} and skipped == {}


def test_a_marker_after_the_header_is_not_a_header(tmp_path):
    body = PY + "\n" * 50 + "# " + "x" * 3000 + "\n# <auto-generated>\n"
    files, _ = _indexed(_repo(tmp_path, {"late.py": body}))
    assert files == {"late.py"}


def test_the_webforms_fixture_still_merges_its_designer_file():
    symbols, _ = parsing.parse_repo(os.path.join(os.path.dirname(__file__), "fixtures",
                                                 "webforms_app"))
    page = next(s for s in symbols if s.id == "Acme.Web.Orders.OrderList")
    assert "OrderList.aspx.designer.cs" in page.path


def test_skipping_can_be_turned_off(tmp_path, monkeypatch):
    monkeypatch.setenv("INDEX_SKIP_GENERATED", "0")
    files, skipped = _indexed(_repo(tmp_path, {"api/x_pb2.py": PY, "Proxy.cs": AUTO + CS.format("P")}))
    assert files == {"api/x_pb2.py", "Proxy.cs"} and skipped == {}


def test_paths_can_be_excluded_by_glob(tmp_path, monkeypatch):
    monkeypatch.setenv("INDEX_EXCLUDE", "legacy/*, *_old.py")
    files, skipped = _indexed(_repo(tmp_path, {"legacy/a.py": PY, "b_old.py": PY, "c.py": PY}))
    assert files == {"c.py"}
    assert skipped == {"legacy/a.py": "excluded by INDEX_EXCLUDE",
                       "b_old.py": "excluded by INDEX_EXCLUDE"}


def test_exclusion_applies_even_with_generated_skipping_off(tmp_path, monkeypatch):
    monkeypatch.setenv("INDEX_SKIP_GENERATED", "0")
    monkeypatch.setenv("INDEX_EXCLUDE", "tmp/*")
    files, _ = _indexed(_repo(tmp_path, {"tmp/a.py": PY, "b.py": PY}))
    assert files == {"b.py"}


def test_vendored_wwwroot_lib_is_skipped(tmp_path):
    """This entry was listed before but could never match a single folder name."""
    files, _ = _indexed(_repo(tmp_path, {"wwwroot/lib/chart/chart.js": "function c() {}\n",
                                         "wwwroot/js/site.js": "function s() {}\n"}))
    assert files == {"wwwroot/js/site.js"}


def test_parse_repo_reports_what_it_skipped(tmp_path):
    stats = {}
    parsing.parse_repo(_repo(tmp_path, {"a_pb2.py": PY, "b.py": PY}), stats)
    assert stats["skipped"] == [("a_pb2.py", "generated (file name)")]


def test_impact_names_a_changed_file_it_skipped(tmp_path):
    """A fake header hides a file from the graph. A change to it must still be visible."""
    def git(*a):
        subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", "-C", str(tmp_path), *a],
                       check=True, capture_output=True)

    git("init", "-q")
    (tmp_path / "real.py").write_text(PY)
    (tmp_path / "sneaky.py").write_text("# Code generated by tool. DO NOT EDIT.\n" + PY)
    git("add", ".")
    git("commit", "-qm", "x")
    skipped = []
    symbols = impact._parse_at(str(tmp_path), "HEAD", ["real.py", "sneaky.py"], skipped)
    assert {s.path for s in symbols} == {"real.py"}
    assert skipped == ["sneaky.py"]
